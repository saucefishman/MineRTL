import json
from dataclasses import dataclass, field

# Yosys JSON netlist format: https://github.com/YosysHQ-Docs/yosys-cmd-ref/blob/main/source/cmd/write_json.rst
# Plain slotted classes rather than pydantic models: a netlist holds millions of these, and the models cost ~4x the
# bytes (a validated 200 MB netlist took 1 GB, a slotted one 0.6 GB, with no copy of the parsed JSON on the way).

# Bit vector: ints are net IDs, strings are constants ("0", "1", "x", "z")
Bits = list[int | str]


@dataclass(slots=True)
class Port:
    direction: str  # "input", "output" or "inout"
    bits: Bits


@dataclass(slots=True)
class Cell:
    # 1 = name is auto-generated by Yosys, 0 = user-defined
    hide_name: int
    type: str
    # Parameter values are binary bit-vector strings, e.g. "00000001"
    parameters: dict[str, str]
    connections: dict[str, Bits]
    port_directions: dict[str, str] = field(default_factory=dict)
    attributes: dict[str, str | int] = field(default_factory=dict)


@dataclass(slots=True)
class NetName:
    bits: Bits
    # Values are binary bit-vector strings; "init" is a register's initial value, LSB last
    attributes: dict[str, str | int] = field(default_factory=dict)


@dataclass(slots=True)
class Module:
    ports: dict[str, Port]
    cells: dict[str, Cell]
    netnames: dict[str, NetName] = field(default_factory=dict)


@dataclass(slots=True)
class Netlist:
    creator: str
    modules: dict[str, Module]

    @classmethod
    def from_json(cls, text: str) -> "Netlist":
        """Only what a build reads is kept: netnames with an "init" (the rest name wires for debugging, a quarter of
        the file) and the attributes of $print cells (their source line); other cells' are mostly source locations."""
        raw = json.loads(text)
        modules = {}
        for name in list(raw["modules"]):
            m = raw["modules"].pop(name)  # one module's parsed JSON at a time
            cells = m["cells"]
            for cell_name in list(cells):
                c = cells.pop(cell_name)
                cells[cell_name] = Cell(c["hide_name"], c["type"], c["parameters"], c["connections"],
                                        c.get("port_directions", {}), c.get("attributes", {}) if c["type"] == "$print" else {})
            netnames = {n: NetName(v["bits"], v["attributes"]) for n, v in m.get("netnames", {}).items()
                        if "init" in v.get("attributes", {})}
            modules[name] = Module({n: Port(p["direction"], p["bits"]) for n, p in m["ports"].items()}, cells, netnames)
        return cls(raw.get("creator", ""), modules)
